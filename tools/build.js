// Builds the page from src/ and styles/.
//   app.js          the page's entry (an ES module): the start-up sequence in src/boot/. Loaded by js/loader.js.
//   chunks/*.js     the rest of the application. Named after their content (a changed file gets a new name), so a
//                   page can never mix an old chunk with a new app.js. Pieces that are only needed sometimes load on demand.
//   styles.css      styles/main.css and the files it imports, bundled and minified (the order of the files IS the cascade).
//   index.html      stamped with a build id (so the browser never serves a stale app.js or styles.css) and with
//                   modulepreload hints, so the code downloads while the stock data loads.
// Usage: node tools/build.js            build everything
//        node tools/build.js --check    fail if what is on disk is not what the current sources would produce
const path = require('path'), fs = require('fs'), crypto = require('crypto');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');
const BANNER = '// Built from src/ by tools/build.js (npm run build). Do not edit this file; edit the modules in src/.';
const rd = f => fs.readFileSync(path.join(root, f), 'utf8');

function buildJs(){
  const r = esbuild.buildSync({
    absWorkingDir: root, entryPoints: { app: 'src/boot/start.js' }, bundle: true, splitting: true, format: 'esm', outdir: '.',
    entryNames: '[name]', chunkNames: 'chunks/[name]-[hash]', target: 'es2022', write: false, metafile: true, logLevel: 'warning', legalComments: 'none',
    minifyWhitespace: true, minifySyntax: true,   // function names are kept on purpose: a stack trace pasted from the console stays readable
    banner: { js: BANNER }
  });
  const files = new Map();
  for(const o of r.outputFiles) files.set(path.relative(root, o.path).split(path.sep).join('/'), o.text);
  return { files, meta: r.metafile };
}
function buildCss(){
  const r = esbuild.buildSync({ absWorkingDir: root, entryPoints: ['styles/main.css'], bundle: true, minify: true, write: false, outfile: 'styles.css', logLevel: 'warning', legalComments: 'none' });
  return r.outputFiles[0].text;
}
// What the page should download early: app.js and what it needs at once, plus the application chunk it loads next.
function preloadList(meta){
  const outs = meta.outputs, seen = new Set(), list = [];
  const visit = k => { if(seen.has(k)) return; seen.add(k); list.push(k); for(const i of outs[k].imports) if(i.kind === 'import-statement') visit(i.path); };
  visit('app.js');
  for(const i of outs['app.js'].imports) if(i.kind === 'dynamic-import' && outs[i.path].entryPoint === 'src/main.js') visit(i.path);
  return list;
}
function stampIndex(html, id, preload){
  const links = preload.map(k => '<link rel="modulepreload" href="' + (k === 'app.js' ? 'app.js?v=' + id : k) + '">').join('\n');
  const steps = [
    [/(href="styles\.css\?v=)[0-9a-f]+(")/, '$1' + id + '$2'],
    [/(data-entry="app\.js\?v=)[0-9a-f]+(")/, '$1' + id + '$2'],
    [/<!--build:preload-->[\s\S]*?<!--\/build:preload-->/, () => '<!--build:preload-->\n' + links + '\n<!--/build:preload-->']
  ];
  for(const [re, rep] of steps){ if(!re.test(html)) throw new Error('index.html: cannot find ' + re + ' to stamp'); html = html.replace(re, rep); }
  return html;
}

const { files, meta } = buildJs();
const css = buildCss();
const id = crypto.createHash('sha1').update([...files].sort().map(([k, v]) => k + '\n' + v).join('\n') + '\n' + css).digest('hex').slice(0, 8);
const index = stampIndex(rd('index.html'), id, preloadList(meta));
const outputs = new Map([...files, ['styles.css', css], ['index.html', index]]);

if(process.argv.includes('--check')){
  const bad = [];
  for(const [f, text] of outputs) if(!fs.existsSync(path.join(root, f)) || rd(f) !== text) bad.push(f + ' is out of date');
  const chunkDir = path.join(root, 'chunks');
  for(const f of fs.existsSync(chunkDir) ? fs.readdirSync(chunkDir) : []) if(!outputs.has('chunks/' + f)) bad.push('chunks/' + f + ' is left over');
  if(bad.length){ console.error(bad.join('\n') + '\nrun "npm run build"'); process.exit(1); }
  console.log('build output is up to date (id ' + id + ')');
} else {
  fs.rmSync(path.join(root, 'chunks'), { recursive: true, force: true });
  fs.mkdirSync(path.join(root, 'chunks'), { recursive: true });
  for(const [f, text] of outputs) fs.writeFileSync(path.join(root, f), text);
  const kb = t => (t.length / 1024).toFixed(1) + ' KB';
  console.log('built id ' + id + ': ' + [...outputs].filter(([f]) => f !== 'index.html').map(([f, t]) => f + ' ' + kb(t)).join(', '));
}
